"""Build migrations/0003_body_parts_avoid_colours_seed.sql from the three data CSVs (the CSVs are the source of truth).
Run:  python3 tune/build_seed_sql.py          (writes the file)
      python3 tune/build_seed_sql.py --check  (exit 1 if the file is out of date; used by tests/test_body_parts_avoid_colours.py)
INSERT OR REPLACE, so applying twice is safe. Applies nothing to any database."""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'core'))
import avoid_colours as A
import body_parts as B
from zodiac import SIGNS

OUT = os.path.join(HERE, '..', 'migrations', '0003_body_parts_avoid_colours_seed.sql')


def q(v):
    return "'" + str(v).replace("'", "''") + "'"


def build():
    import json
    L = ['-- 0003_body_parts_avoid_colours_seed.sql', '-- GENERATED by tune/build_seed_sql.py from data/house_body_parts.csv, data/lagna_avoid_colours.csv, data/planet_avoid_colours.csv.',
         '-- Do not edit by hand: edit the CSV and re-run the script. Needs 0002 first. NOT applied to any live database by the PR that adds it.',
         "-- Every row is status 'DEFAULT, owner to confirm'.", '']
    for h, r in sorted(B.load_table().items()):
        L.append('INSERT OR REPLACE INTO ref_house_body_part (house_no, natural_sign, primary_part, extended_parts, basis, status) VALUES (%d, %s, %s, %s, %s, %s);'
                 % (h, q(r['natural_sign']), q(r['primary_part']), q(json.dumps(r['extended_parts'])), q(r['basis']), q(r['status'])))
    L.append('')
    order = {}
    for r in A.load_lagna_table():
        order[r['lagna_sign']] = order.get(r['lagna_sign'], 0) + 1
        L.append('INSERT OR REPLACE INTO ref_lagna_avoid_colour (lagna_no, lagna_sign, avoid_order, avoid_planet, avoid_colour, houses_lorded, reason, status) VALUES (%d, %s, %d, %s, %s, %s, %s, %s);'
                 % (SIGNS.index(r['lagna_sign']) + 1, q(r['lagna_sign']), order[r['lagna_sign']], q(r['avoid_planet']), q(r['avoid_colour']),
                    q(json.dumps(r['houses_lorded'])), q(r['reason']), q(r['status'])))
    L.append('')
    n = {}
    for r in A.load_planet_table():
        n[r['planet']] = n.get(r['planet'], 0) + 1
        L.append('INSERT OR REPLACE INTO ref_planet_avoid_colour (planet_no, planet, enemy_no, enemy_planet, avoid_colour, reason, status) VALUES (%d, %s, %d, %s, %s, %s, %s);'
                 % (A.PNAME.index(r['planet']), q(r['planet']), A.PNAME.index(r['enemy_planet']), q(r['enemy_planet']), q(r['avoid_colour']), q(r['reason']), q(r['status'])))
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        sys.exit(0 if cur == text else 1)
    open(OUT, 'w', encoding='utf-8').write(text)
    print('wrote', os.path.relpath(OUT), text.count('INSERT'), 'rows')
